"""
Aim 4: writes AIM4_TABLES.md from the saved outputs.

Cross checking the Aim 2 write up once found four errors in 116 hand typed
numbers, and two audit passes over Aim 3 found 47 in 1,067. So every number in
the tables is read from the file that produced it and can't drift from the run.
The write up just quotes these tables.

Don't edit the generated file by hand, just rerun:
    python3 report_aim4.py
"""

import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import common4 as C                                      # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "AIM4_TABLES.md")


def load_json(name):
    p = os.path.join(C.RESULTS, name)
    return json.load(open(p)) if os.path.exists(p) else None


def load_csv(name):
    p = os.path.join(C.RESULTS, name)
    return pd.read_csv(p) if os.path.exists(p) else None


def section(lines, title):
    lines.append("")
    lines.append(f"## {title}")
    lines.append("")


def main():
    L = ["# Aim 4 tables",
         "",
         "**Generated by `aim4/report_aim4.py` from the saved output files. Do "
         "not edit by hand.**",
         "",
         "Every figure below is read from the file named at the end of its "
         "table, so it cannot drift from the run that produced it. Method and "
         "reasoning are in [AIM4_METHODS.md](AIM4_METHODS.md); the "
         "interpretation is in [AIM4_RESULTS.md](AIM4_RESULTS.md)."]

    # --- 1. the models explained ---
    section(L, "1. The models explained, and whether they are the published "
               "models")
    s = load_json("shap_summary.json")
    if s:
        L += ["| model | specification | refit AUC | published AUC | "
              "difference | hyperparameters | additivity violation | units |",
              "|---|---|---|---|---|---|---|---|"]
        # read from the saved summary because how a model's hyperparameters
        # were obtained can change between runs. The forest moved from a fixed
        # configuration to a recovered one after verification check B3 failed,
        # and a hardcoded column would still describe it the old way.
        for r in s:
            how = r.get("hyperparameters", "not recorded")
            L.append(
                f"| {r['model']} | {r['specification']} | "
                f"{r['auc_refit']:.4f} | {r['auc_published']:.4f} | "
                f"{r['auc_difference']:+.4f} | {how} | "
                f"{r['worst_additivity_violation']:.1e} | {r['units']} |")
        L += ["", "Source: `shap_summary.json`."]

    # --- 2. classical importance ---
    imp = load_csv("shap_importance_all.csv")
    if imp is not None:
        for spec in C.SPECS:
            section(L, f"2. Feature contributions, {spec}")
            L += ["| rank | logistic regression | mean abs | direction | "
                  "xgboost | mean abs | random forest | mean abs |",
                  "|---|---|---|---|---|---|---|---|"]
            per = {}
            for model in C.CLASSICAL_MODELS:
                t = imp[(imp["model"] == model)
                        & (imp["specification"] == spec)]
                per[model] = t.sort_values("mean_abs_shap",
                                           ascending=False).reset_index()
            n = min(12, min(len(v) for v in per.values())) if per else 0
            for i in range(n):
                lr = per["logistic_regression"].iloc[i]
                xg = per["xgboost"].iloc[i]
                rf = per["random_forest"].iloc[i]
                L.append(
                    f"| {i + 1} | {lr['feature']} | {lr['mean_abs_shap']:.4f} "
                    f"| {lr['value_shap_spearman']:+.2f} | {xg['feature']} | "
                    f"{xg['mean_abs_shap']:.4f} | {rf['feature']} | "
                    f"{rf['mean_abs_shap']:.5f} |")
            L += ["",
                  "Contributions are mean absolute SHAP over the cohort, out "
                  "of fold. The direction column is the rank correlation "
                  "between a participant's value of the feature and the "
                  "contribution it made, so plus one means higher values raise "
                  "risk. Magnitudes are not comparable between the forest, "
                  "whose values are in probability units, and the other two, "
                  "which are in log odds.",
                  "", "Source: `shap_importance_all.csv`."]

    # --- 3. cross model agreement ---
    ag = load_csv("cross_model_agreement.csv")
    if ag is not None:
        section(L, "3. Do the three classical models agree about what matters?")
        L += ["| specification | model A | model B | Spearman | p | "
              "features | top five overlap |", "|---|---|---|---|---|---|---|"]
        for _, r in ag.iterrows():
            L.append(f"| {r['specification']} | {r['model_a']} | "
                     f"{r['model_b']} | {r['spearman']:+.3f} | "
                     f"{r['p_value']:.3g} | {int(r['n_features'])} | "
                     f"{int(r['top5_overlap'])} of 5 |")
        L += ["", "Source: `cross_model_agreement.csv`."]

    # --- 4. collinearity ---
    g = load_csv("grouped_contributions.csv")
    if g is not None:
        section(L, "4. Collinearity: contributions summed within correlated "
                   "clusters")
        sub = g[(g["model"] == "logistic_regression")
                & (g["specification"] == "obm_only")].head(10)
        L += [f"Clusters are connected components of the graph joining features "
              f"that correlate at absolute Spearman at least "
              f"{0.80:.2f}. The cancellation ratio is the magnitude of the "
              f"cluster's summed contribution divided by the sum of its "
              f"members' magnitudes: one means the members agree, near zero "
              f"means they cancel and their individual contributions must not "
              f"be quoted.",
              "",
              "| rank | size | summed mean abs | sum of member mean abs | "
              "cancellation | members |", "|---|---|---|---|---|---|"]
        for _, r in sub.iterrows():
            L.append(f"| {int(r['rank'])} | {int(r['size'])} | "
                     f"{r['mean_abs_shap_summed']:.4f} | "
                     f"{r['sum_of_member_mean_abs']:.4f} | "
                     f"{r['cancellation_ratio']:.3f} | {r['members']} |")
        worst = g[g["size"] > 1].nsmallest(6, "cancellation_ratio")
        L += ["", "The clusters whose members cancel most, across all models "
                  "and specifications:", "",
              "| model | specification | cancellation | members |",
              "|---|---|---|---|"]
        for _, r in worst.iterrows():
            L.append(f"| {r['model']} | {r['specification']} | "
                     f"{r['cancellation_ratio']:.3f} | {r['members']} |")
        L += ["", "Source: `grouped_contributions.csv`, logistic regression on "
                  "the oximetry only specification."]

    # --- 5. deep attribution method agreement ---
    meta = load_json(f"deep_attrib_{C.DEEP_ARM}.json")
    if meta:
        section(L, "5. The three attribution methods against each other")
        L += ["| quantity | value | what it establishes |", "|---|---|---|",
              f"| participants explained | {meta['n_explained']} | the whole "
              f"analysis cohort, out of fold |",
              f"| worst reconstruction error of the exact decomposition | "
              f"{meta['worst_exact_reconstruction_error']:.2e} | the step "
              f"decomposition is the network's own arithmetic, not an "
              f"approximation of it |"]
        if "ig_completeness_abs_worst" in meta:
            L.append(
                f"| worst integrated gradients completeness error | "
                f"{meta['ig_completeness_abs_worst']:.2e} logits | the sample "
                f"level attribution sums to the change in logit it claims, "
                f"within {meta.get('ig_abs_tolerance')} |")
            L.append(
                f"| median integration steps, own median baseline | "
                f"{meta.get('flat_own_steps_median')} | refined per "
                f"participant until completeness held |")
            if "flat_97_steps_median" in meta:
                L.append(
                    f"| median integration steps, fixed 97 percent baseline | "
                    f"{meta.get('flat_97_steps_median')} | the longer path "
                    f"needs more steps, and gets them |")
            L.append(
                f"| integrated gradients against the exact decomposition | "
                f"median r {meta['ig_vs_exact_pearson_median']:+.3f} | the two "
                f"attribute to different things: input samples against feature "
                f"positions, separated by a 70 minute receptive field |")
        L += [f"| gradient times activation against the exact decomposition | "
              f"median r {meta['gxa_vs_exact_pearson_median']:+.3f} | the "
              f"gradient is faithful; two independently coded routes to the "
              f"same quantity agree |",
              f"| Grad-CAM against the exact decomposition | median r "
              f"{meta['cam_vs_exact_pearson_median']:+.3f} | averaging "
              f"gradients over steps, which is what makes Grad-CAM Grad-CAM, "
              f"costs most of its faithfulness on this architecture |",
              f"| backend faults | {meta['faults']} | published rather than "
              f"hidden |",
              "", f"Source: `deep_attrib_{C.DEEP_ARM}.json`."]

    # --- 6. attribution by saturation ---
    sp = load_csv("attribution_by_spo2.csv")
    if sp is not None:
        section(L, "6. What the network reads: attribution by saturation level")
        L += ["| SpO2 band, percent | minutes per night | signed total | "
              "share of absolute attribution | share of time | enrichment |",
              "|---|---|---|---|---|---|"]
        for _, r in sp.iterrows():
            L.append(f"| {r['spo2_bin']} | {r['minutes_per_night']:.1f} | "
                     f"{r['signed_total']:+.2f} | {r['share_of_abs']:.3f} | "
                     f"{r['share_of_time']:.3f} | {r['enrichment']:.2f} |")
        L += ["",
              "Signed totals are summed over the cohort, so a positive band is "
              "one where time spent raises the predicted risk. Enrichment is "
              "the share of absolute attribution divided by the share of time: "
              "one means the band is treated like any other, above one means "
              "the network concentrates there.",
              "", "Source: `attribution_by_spo2.csv`."]

    # --- 7. scored events and sleep stage ---
    h = load_json("headtohead.json")
    if h:
        section(L, "7. Attribution inside scored events and by sleep stage")
        L += ["| quantity | value |", "|---|---|"]
        if "desat_enrichment_median" in h:
            L.append(f"| enrichment inside technician scored desaturations | "
                     f"{h['desat_enrichment_median']:.3f} |")
        if "resp_enrichment_median" in h:
            L.append(f"| enrichment inside scored apnoeas and hypopnoeas | "
                     f"{h['resp_enrichment_median']:.3f} |")
        if "rem_share_of_attribution" in h:
            L.append(f"| REM share of absolute attribution | "
                     f"{h['rem_share_of_attribution']:.3f} |")
            L.append(f"| REM share of analysable sleep time | "
                     f"{h['rem_share_of_time']:.3f} |")
            L.append("| REM share the architecture allocates by design | "
                     "0.500 |")
        L += ["",
              "The scored events come from the NSRR annotation files and are "
              "independent of anything this project computed from the signal. "
              "The REM comparison is against the half of the pooled vector the "
              "architecture allocates to REM, not against REM's share of the "
              "night, because the pooling fixes the former by design.",
              "", "Source: `headtohead.json`."]

    # --- 8. occlusion ---
    occ = load_json(f"occlusion_{C.DEEP_ARM}.json")
    if occ:
        section(L, "8. The occlusion test: does the model behave as the "
                   "attribution says?")
        L += [f"Occluding {occ['fraction']:.0%} of the valid steps, about "
              f"{occ['minutes_occluded']:.0f} minutes per night, on "
              f"{occ['n']} participants. Random occlusion is the mean of "
              f"{occ['n_random_draws']} draws per participant.", "",
              "| steps occluded | mask cleared, median change in logit | "
              "mask kept, median change |", "|---|---|---|"]
        for name, label in (("top", "most positively attributed"),
                            ("random", "chosen at random"),
                            ("bottom", "most negatively attributed")):
            L.append(f"| {label} | {occ[f'd_{name}_cleared_median']:+.4f} | "
                     f"{occ[f'd_{name}_kept_median']:+.4f} |")
        L += ["",
              "| check | mask cleared | mask kept |", "|---|---|---|",
              f"| the ordering top below random below bottom holds for | "
              f"{occ['ordering_holds_cleared']:.1%} of participants | "
              f"{occ['ordering_holds_kept']:.1%} of participants |",
              f"| predicted against measured drop, Spearman | "
              f"{occ['predicted_vs_measured_spearman_cleared']:+.3f} | "
              f"{occ['predicted_vs_measured_spearman_kept']:+.3f} |",
              "",
              "Clearing the mask removes the stretch from the pooled averages "
              "as wake and artefact already are, which also changes the "
              "denominators; keeping it holds the denominators fixed so the "
              "measured change is attributable to the content alone. Both are "
              "reported because they answer slightly different questions.",
              "", f"Source: `occlusion_{C.DEEP_ARM}.json`."]

    # --- 9. reducibility ---
    red = load_csv("deep_reducibility.csv")
    if red is not None:
        section(L, "9. How much of the deep score do tabular features "
                   "reproduce?")
        L += ["| predictors | n | out of fold R squared | in sample R squared "
              "| Spearman |", "|---|---|---|---|---|"]
        for _, r in red.iterrows():
            L.append(f"| {r['predictors']} | {int(r['n_predictors'])} | "
                     f"{r['r2_out_of_fold']:+.4f} | "
                     f"{r['r2_in_sample_mean']:+.4f} | {r['spearman']:+.3f} |")
        L += ["",
              "Ridge regression of the deep score on each predictor set, with "
              "the penalty chosen inside each training fold and the R squared "
              "computed on held out participants. The in sample column is the "
              "same quantity on the training rows, so the gap between the two "
              "is how much of an apparent agreement is overfitting.",
              "", "Source: `deep_reducibility.csv`."]

    # --- 10. SHAP rank vs association with the deep score ---
    br = load_csv("biomarker_bridge.csv")
    if br is not None and h and "bridge_rank_agreement" in h:
        section(L, "10. Do the two pipelines weight the same biomarkers?")
        r = h["bridge_rank_agreement"]
        L += [f"Rank agreement between a biomarker's SHAP importance in the "
              f"oximetry only logistic regression and its association with the "
              f"deep score: Spearman {r['rho']:+.3f}, p = "
              f"{r['p_value']:.3g}, over {r['n']} biomarkers.", "",
              "| biomarker | Spearman with the deep score | SHAP rank | "
              "deep rank |", "|---|---|---|---|"]
        for _, rr in br.head(12).iterrows():
            L.append(f"| {rr['feature']} | {rr['spearman_with_deep']:+.3f} | "
                     f"{int(rr['shap_rank'])} | {int(rr['deep_rank'])} |")
        L += ["", "Source: `biomarker_bridge.csv`, `headtohead.json`."]

    # --- 11. contrast C3 ---
    if h and h.get("contrast_c3"):
        c3 = h["contrast_c3"]
        section(L, "11. Contrast C3: does the deep score add to the clinical "
                   "variables and the biomarkers together?")
        t, d = c3["coefficient_test"], c3["delta_auc"]
        L += ["| quantity | value |", "|---|---|",
              f"| clinical plus biomarkers, AUC | {c3['auc_base']:.4f} |",
              f"| the same plus the deep score, AUC | "
              f"{c3['auc_with_deep']:.4f} |",
              f"| change in AUC | {c3['delta_auc_point']:+.4f} |",
              f"| 90 percent interval on the change | "
              f"[{d['ci90_lo']:+.4f}, {d['ci90_hi']:+.4f}] |",
              f"| pre-registered equivalence margin | "
              f"plus or minus {c3['equivalence_margin']} |",
              f"| coefficient on the deep score, per standard deviation | "
              f"{t['beta']:+.4f} |",
              f"| odds ratio | {t['or_per_sd']:.4f} "
              f"[{t['or_ci_lo']:.4f}, {t['or_ci_hi']:.4f}] |",
              f"| likelihood ratio test | chi squared {t['lr_chi2']:.3f}, "
              f"p = {t['p_value']:.4g} |",
              f"| participants, events | {c3['n']}, {c3['n_events']} |",
              "", "Source: `headtohead.json`."]

    # --- 12. verification ---
    v = load_csv("verification_aim4.csv")
    if v is not None:
        section(L, "12. Verification")
        ran = v[v["pass"].notna()]
        n_ok = int(ran["pass"].astype(str).isin(["True", "true"]).sum()) \
            if ran["pass"].dtype == object else int(ran["pass"].sum())
        L += [f"{n_ok} of {len(ran)} checks pass; "
              f"{int(v['pass'].isna().sum())} were not applicable.", "",
              "| group | check | result | detail |", "|---|---|---|---|"]
        for _, r in v.iterrows():
            state = "not run" if pd.isna(r["pass"]) else (
                "pass" if r["pass"] in (True, "True", "true") else "FAIL")
            L.append(f"| {r['group']} | {r['check']} | {state} | "
                     f"{str(r['detail'])[:150]} |")
        L += ["", "Source: `verification_aim4.csv`."]

    text = "\n".join(L) + "\n"
    if C.EM_DASH in text:
        # compared by code point because a blanket find and replace once
        # rewrote this guard's own test string, after which it fired on every
        # comma and quietly refused to write the file for a day
        raise SystemExit("refusing to write: the generated text contains an "
                         "em dash")
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {OUT}  ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
